// Translate a raw English nav/group label into the current language.
// Falls back to the raw label (e.g. entity names, future app labels) when unknown.
export function shellLabel(t, label) {
  const key = NAV_LABEL_KEYS[label] || GROUP_LABEL_KEYS[label];
  return key ? t(key) : label;
}
