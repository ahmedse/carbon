import { chromium } from 'playwright';
const BASE = 'http://127.0.0.1:5179';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
page.setDefaultTimeout(30000);
await page.goto(`${BASE}/login`, { waitUntil: 'domcontentloaded' });
await page.getByLabel('Username').fill('ahmed');
await page.getByLabel('Password').fill('AdminPa_132');
await page.getByRole('button', { name: 'Sign in' }).click();
await page.waitForTimeout(3000);
await page.goto(`${BASE}/admin/ai/workspace`, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(6000);
const info = await page.evaluate(() => {
  const lbs = [...document.querySelectorAll('[role="listbox"]')].map(l => ({ aria: l.getAttribute('aria-label'), vis: !!l.offsetParent, opts: l.querySelectorAll('[role="option"]').length }));
  const crumbs = [...document.querySelectorAll('nav[aria-label="Breadcrumb navigation"] a, nav[aria-label="Breadcrumb navigation"] [aria-current="page"]')].map(a => a.innerText.trim());
  const current = document.querySelector('[aria-current="page"]')?.innerText?.trim();
  return { listboxes: lbs, crumbs, currentPageCrumb: current };
});
console.log(JSON.stringify(info, null, 2));
await browser.close();
